import ghidra.app.script.GhidraScript;
import ghidra.app.decompiler.DecompInterface;
import ghidra.app.decompiler.DecompileResults;
import ghidra.program.model.address.Address;
import ghidra.program.model.listing.Function;
import ghidra.program.model.listing.Instruction;
import ghidra.program.model.listing.InstructionIterator;
import ghidra.program.model.scalar.Scalar;
import ghidra.program.model.symbol.Reference;
import ghidra.program.model.symbol.ReferenceIterator;
import java.io.FileWriter;
import java.io.Writer;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeSet;

public class ExportAnnotated extends GhidraScript {

    long[] targets = {
        0x10052308L, // launcher / safemode decision
        0x100522a8L, // enter safemode
        0x10154790L, // handle upgrade / version gate
        0x10156280L, // parse <firmware_version> entry
        0x10155ed4L, // parse version block
        0x10155fd8L, // parse <partitions>
        0x10156100L, // parse partitions (alt/older)
        0x10153ba0L, // per-partition write + verify
        0x10154284L, // verify-all + retry
        0x101537fcL, // hw crc over a range
        0x100f458cL, // read FW_VERS (current version)
        0x10055a44L, // read OTA_UPG_FLAG
        0x10055af8L  // read OTA_UPG_TYPE
    };

    String readCStr(Address a) {
        try {
            StringBuilder sb = new StringBuilder();
            for (int i = 0; i < 160; i++) {
                byte b = getByte(a.add(i));
                if (b == 0) break;
                if (b < 32 || b > 126) return null;
                sb.append((char) b);
            }
            return sb.length() >= 3 ? sb.toString() : null;
        } catch (Exception e) {
            return null;
        }
    }

    String resolve(long v) {
        Address a = toAddr(v);
        String s = readCStr(a);
        if (s != null) return s;
        for (Reference r : currentProgram.getReferenceManager().getReferencesFrom(a)) {
            Address t = r.getToAddress();
            s = readCStr(t);
            if (s != null) return s;
        }
        try {
            int ptr = getInt(a);
            if (ptr != 0) {
                s = readCStr(toAddr(ptr & 0xFFFFFFFFL));
                if (s != null) return s;
            }
        } catch (Exception e) { }
        return null;
    }

    public void run() throws Exception {
        DecompInterface dec = new DecompInterface();
        dec.openProgram(currentProgram);
        StringBuilder sb = new StringBuilder();

        sb.append(
            "/*\n" +
            " * CMF Watch Pro 2 (board jx402_01_3089c, Actions ATS3089C, FreeRTOS) OTA - annotated decompilation\n" +
            " * app.bin (2.45 MB Thumb) loaded at 0x10000000.  Generated by ExportAnnotated.java (Ghidra 12.1.4).\n" +
            " *\n" +
            " * AOTA container (fwkit.py):\n" +
            " *   0x000  header 0x200: 'AOTA' | crc32(hdr[0x08:0x400]) @0x04 | f0=0x04000100 @0x08 |\n" +
            " *          toc_count @0x0c | f10=0x04000200 @0x10 | data_end @0x14 | crc32(img[0x400:data_end]) @0x18 |\n" +
            " *          version_name@0x40[32] | board_name@0x60[32]\n" +
            " *   0x200  TOC entries: name[16]|off|size|flags|crc32(stored blob)\n" +
            " *   0x400  ota.xml manifest; partition blobs 0x200-aligned; trailing 'AGPS' block\n" +
            " *   blobs are LZMA-chunked (magic 'LZMA'|u32|u32 comp|u32 uncomp|XZ preset-6); TEMP blk=0x200000 else 0x8000\n" +
            " *\n" +
            " * Version gate (FUN_10154790, 'handle upgrade'):\n" +
            " *   - refuses if state != OTA_INIT or ota.xml missing\n" +
            " *   - strcmp(current board_name, ota board_name) != 0  -> 'unmatched board name, skip ota'\n" +
            " *   - if !force (flags bit2) and ota_version_code <= current_version_code -> 'ota image is same or older, skip ota'\n" +
            " *   - flags bit0/1 = erase-old / full-write, force = flags bit2\n" +
            " *   - NO signature; integrity is per-file CRC32 only (FUN_10153ba0 write+verify, FUN_10154284 verify+retry)\n" +
            " * Launcher (FUN_10052308): if OTA_UPG_FLAG=='run' or res_chk/ver_chk != 0 -> enter safemode (OTA UI) on next boot.\n" +
            " */\n\n");

        for (long t : targets) {
            Address a = toAddr(t);
            Function f = getFunctionAt(a);
            if (f == null) { sb.append(String.format("// no function at %x%n%n", t)); continue; }
            sb.append("// ==================================================================\n");
            sb.append(String.format("// %s @ %s%n", f.getName(), a));
            sb.append("// ==================================================================\n");
            DecompileResults r = dec.decompileFunction(f, 90, monitor);
            if (r != null && r.decompileCompleted()) {
                sb.append(r.getDecompiledFunction().getC()).append("\n");
            } else {
                sb.append("// decompile failed\n");
            }

            // resolve DAT_ constants used in this function to strings
            Map<Long, String> consts = new LinkedHashMap<>();
            InstructionIterator it = currentProgram.getListing().getInstructions(f.getBody(), true);
            while (it.hasNext()) {
                Instruction ins = it.next();
                for (int op = 0; op < ins.getNumOperands(); op++) {
                    for (Object o : ins.getOpObjects(op)) {
                        long v;
                        if (o instanceof Scalar) v = ((Scalar) o).getUnsignedValue();
                        else if (o instanceof Address) v = ((Address) o).getOffset();
                        else continue;
                        if (v < 0x10000000L || v > 0x10300000L) continue;
                        if (consts.containsKey(v)) continue;
                        String s = resolve(v);
                        if (s != null) consts.put(v, s);
                    }
                }
            }
            if (!consts.isEmpty()) {
                sb.append("// ---- string legend ----\n");
                List<Long> keys = new ArrayList<>(consts.keySet());
                java.util.Collections.sort(keys);
                for (Long k : keys) {
                    sb.append(String.format("//   DAT_%08x = \"%s\"%n", k, consts.get(k)));
                }
            }
            sb.append("\n");
        }

        String out = "out/annotated_ota.c";
        try (Writer w = new FileWriter(out)) { w.write(sb.toString()); }
        println("wrote " + out + " (" + sb.length() + " chars)");
    }
}
